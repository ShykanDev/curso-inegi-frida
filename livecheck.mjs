import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage()
const errores = []
p.on('pageerror', e => errores.push(e.message))
p.on('console', m => { if (m.type()==='error') errores.push(m.text()) })
const resp = await p.goto('https://shykandev.github.io/curso-inegi-frida/', { waitUntil: 'networkidle', timeout: 60000 })
console.log('STATUS', resp.status())
await p.waitForTimeout(1500)
const t = (await p.textContent('body')) ?? ''
console.log('saludo:', t.includes('Hola, Frida'))
console.log('seis modulos:', ['Módulo 0','Módulo 5'].every(x=>t.includes(x)))
await p.goto('https://shykandev.github.io/curso-inegi-frida/#/modulo/1', { waitUntil: 'networkidle' })
await p.waitForTimeout(1500)
const reto = p.getByRole('region', { name: 'Reto 1.1' })
const tabla = reto.locator('table')
const fila = tabla.locator('tbody tr').first()
await fila.locator('td').nth(2).click()
await p.waitForTimeout(300)
await p.keyboard.type('Azcapotzalco')
await p.keyboard.press('Enter')
await p.waitForTimeout(400)
console.log('simulador escribe:', ((await fila.locator('td').nth(2).textContent()) ?? '').trim() === 'Azcapotzalco')
await p.goto('https://shykandev.github.io/curso-inegi-frida/#/modulo/1', { waitUntil: 'networkidle' })
await p.waitForTimeout(600)
await p.getByRole('button', { name: /1\.3 · SUMA/ }).click()
await p.waitForTimeout(600)
const r3 = p.getByRole('region', { name: 'Reto 1.3' })
const f7 = r3.locator('table tbody tr').last()
await f7.locator('td').nth(2).click()
await p.waitForTimeout(200)
await p.keyboard.type('=SUMA(B2:B6)')
await p.keyboard.press('Enter')
await p.waitForTimeout(400)
console.log('SUMA en vivo:', ((await f7.locator('td').nth(2).textContent()) ?? '').trim() === '70')
console.log('errores:', errores.filter(e=>!e.includes('favicon')).length, errores.slice(0,3))
await p.screenshot({ path: 'live.png' })
await b.close()
